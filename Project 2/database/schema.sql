-- ============================================
-- MUSIC STREAMING PLATFORM
-- COCKROACHDB / POSTGRESQL SCHEMA
-- ============================================

DROP TABLE IF EXISTS payment CASCADE;
DROP TABLE IF EXISTS episode CASCADE;
DROP TABLE IF EXISTS podcast CASCADE;
DROP TABLE IF EXISTS user_artist CASCADE;
DROP TABLE IF EXISTS playlist_song CASCADE;
DROP TABLE IF EXISTS song CASCADE;
DROP TABLE IF EXISTS album CASCADE;
DROP TABLE IF EXISTS device CASCADE;
DROP TABLE IF EXISTS subscription CASCADE;
DROP TABLE IF EXISTS playlist CASCADE;
DROP TABLE IF EXISTS podcast_creator CASCADE;
DROP TABLE IF EXISTS artist CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    user_id INT GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    last_name VARCHAR(50),
    email VARCHAR(150) NOT NULL,
    phone_no VARCHAR(20),
    gender VARCHAR(20),
    dob DATE,
    password VARCHAR(255),
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

CREATE TABLE artist (
    artist_id INT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(150) NOT NULL,
    bio TEXT,
    social_media VARCHAR(500),
    CONSTRAINT pk_artist PRIMARY KEY (artist_id)
);

CREATE TABLE podcast_creator (
    creator_id INT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(150) NOT NULL,
    bio TEXT,
    CONSTRAINT pk_podcast_creator PRIMARY KEY (creator_id),
    CONSTRAINT uq_creator_email UNIQUE (email)
);

CREATE TABLE playlist (
    playlist_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    playlist_name VARCHAR(150) NOT NULL,
    created_date DATE DEFAULT current_date,
    visibility VARCHAR(20) DEFAULT 'PRIVATE',
    CONSTRAINT pk_playlist PRIMARY KEY (playlist_id),
    CONSTRAINT fk_playlist_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT chk_playlist_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE'))
);

CREATE TABLE subscription (
    subscription_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    plan_type VARCHAR(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    CONSTRAINT pk_subscription PRIMARY KEY (subscription_id),
    CONSTRAINT fk_subscription_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

CREATE TABLE device (
    device_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    os VARCHAR(50),
    device_type VARCHAR(50),
    CONSTRAINT pk_device PRIMARY KEY (device_id),
    CONSTRAINT fk_device_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

CREATE TABLE album (
    album_id INT GENERATED BY DEFAULT AS IDENTITY,
    artist_id INT NOT NULL,
    album_title VARCHAR(200) NOT NULL,
    release_date DATE,
    cover_page VARCHAR(500),
    CONSTRAINT pk_album PRIMARY KEY (album_id),
    CONSTRAINT fk_album_artist FOREIGN KEY (artist_id) REFERENCES artist (artist_id)
);

CREATE TABLE song (
    song_id INT GENERATED BY DEFAULT AS IDENTITY,
    album_id INT,
    artist_id INT NOT NULL,
    name VARCHAR(200) NOT NULL,
    duration INT,
    release_date DATE,
    audio_url VARCHAR(500),
    CONSTRAINT pk_song PRIMARY KEY (song_id),
    CONSTRAINT fk_song_album FOREIGN KEY (album_id) REFERENCES album (album_id),
    CONSTRAINT fk_song_artist FOREIGN KEY (artist_id) REFERENCES artist (artist_id)
);

CREATE TABLE playlist_song (
    playlist_id INT NOT NULL,
    song_id INT NOT NULL,
    added_date DATE DEFAULT current_date,
    CONSTRAINT pk_playlist_song PRIMARY KEY (playlist_id, song_id),
    CONSTRAINT fk_ps_playlist FOREIGN KEY (playlist_id) REFERENCES playlist (playlist_id) ON DELETE CASCADE,
    CONSTRAINT fk_ps_song FOREIGN KEY (song_id) REFERENCES song (song_id) ON DELETE CASCADE
);

CREATE TABLE user_artist (
    user_id INT NOT NULL,
    artist_id INT NOT NULL,
    followed_date DATE DEFAULT current_date,
    CONSTRAINT pk_user_artist PRIMARY KEY (user_id, artist_id),
    CONSTRAINT fk_ua_user FOREIGN KEY (user_id) REFERENCES app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ua_artist FOREIGN KEY (artist_id) REFERENCES artist (artist_id) ON DELETE CASCADE
);

CREATE TABLE podcast (
    podcast_id INT GENERATED BY DEFAULT AS IDENTITY,
    creator_id INT NOT NULL,
    title VARCHAR(200) NOT NULL,
    language VARCHAR(50),
    release_date DATE,
    description TEXT,
    CONSTRAINT pk_podcast PRIMARY KEY (podcast_id),
    CONSTRAINT fk_podcast_creator FOREIGN KEY (creator_id) REFERENCES podcast_creator (creator_id)
);

CREATE TABLE episode (
    episode_id INT GENERATED BY DEFAULT AS IDENTITY,
    podcast_id INT NOT NULL,
    episode_no INT NOT NULL,
    title VARCHAR(200) NOT NULL,
    duration INT,
    description TEXT,
    release_date DATE,
    audio_url VARCHAR(500),
    CONSTRAINT pk_episode PRIMARY KEY (episode_id),
    CONSTRAINT fk_episode_podcast FOREIGN KEY (podcast_id) REFERENCES podcast (podcast_id) ON DELETE CASCADE,
    CONSTRAINT uq_episode_number UNIQUE (podcast_id, episode_no)
);

CREATE TABLE payment (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY,
    user_id INT NOT NULL,
    subscription_id INT,
    amount DECIMAL(10,2) NOT NULL,
    payment_mode VARCHAR(30),
    payment_date DATE DEFAULT current_date,
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT fk_payment_subscription FOREIGN KEY (subscription_id) REFERENCES subscription (subscription_id),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0)
);
